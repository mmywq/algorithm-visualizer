import type { Transition } from 'framer-motion';

/**
 * Единая «физика» интерфейса. Весь сайт двигается по этим пружинам и кривым, а не по
 * подобранным на глаз числам в каждом компоненте: так переходы ощущаются одинаково.
 *
 * Пружины без отскока (bounce: 0) — для всего, что пользователь делает часто: панели,
 * меню, переключатели, шаги демонстрации. Отскок оставлен только для редких праздничных
 * моментов — новый уровень, достижение, реакции Кэша.
 */
export const spring = {
  /** переключатели, индикаторы, подсветка: коротко и точно */
  snappy: { type: 'spring', duration: 0.28, bounce: 0 },
  /** столбики, узлы и стрелки в демонстрациях: движение должно читаться, но не тормозить шаги */
  viz: { type: 'spring', duration: 0.42, bounce: 0 },
  /** панели, диалоги, карточки, появление блоков */
  smooth: { type: 'spring', duration: 0.5, bounce: 0 },
  /** крупные блоки первого экрана */
  gentle: { type: 'spring', duration: 0.8, bounce: 0 },
  /** редкие праздничные моменты */
  playful: { type: 'spring', duration: 0.6, bounce: 0.35 },
} as const satisfies Record<string, Transition>;

/** Кривые для твинов: ease-out — для появления, ease-in — для ухода, in-out — для смены состояния на месте. */
export const ease = {
  out: [0.22, 1, 0.36, 1],
  in: [0.55, 0, 1, 0.45],
  inOut: [0.65, 0, 0.35, 1],
} as const;

/** Уход всегда тише появления: внимание уже переключилось на то, что приходит следом. */
export const exitFast: Transition = { duration: 0.16, ease: ease.in };

/**
 * Появление «из фокуса»: прозрачность, небольшой подъём и размытие, которое уходит в резкость.
 * Размытие — только для небольших элементов: на целой странице оно дорого обходится видеокарте.
 */
export const materialize = {
  initial: { opacity: 0, y: 10, filter: 'blur(4px)' },
  animate: { opacity: 1, y: 0, filter: 'blur(0px)' },
  exit: { opacity: 0, y: -4, filter: 'blur(2px)', transition: exitFast },
} as const;
