const normalizePath = (path: string): string => (path.length > 1 ? path.replace(/\/+$/, '') : path);

export const findEntryByPath = (path: string): AlgorithmEntry | undefined => {
  const normalized = normalizePath(path);
  return catalog.find((entry) => entry.path === normalized);
};

export const findLegacyEntry = (path: string): AlgorithmEntry | undefined => {
  const normalized = normalizePath(path);
  return catalog.find((entry) => entry.legacyPaths?.includes(normalized) === true);
};

export const entriesOfCategory = (categoryId: CategoryId): readonly AlgorithmEntry[] => catalog.filter((entry) => entry.category === categoryId);

